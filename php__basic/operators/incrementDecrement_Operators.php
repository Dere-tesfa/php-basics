<?php

//Increment and decrement operators are used to increase or decrease the value of a variable by one.

$x=10;
$x++;//Post-increment: returns the value before incrementing//10
++$x;//Pre-increment: returns the value after incrementing //12
$x--;//Post-decrement: returns the value before decrementing //12
--$x;//Pre-decrement: returns the value after decrementing //10



?>